package Packages;

public class TravelPackage {
    private String flightInformation;
    private String hotelInformation;
    private String excursionInformation;

    public void setFlightInformation(String flightInformation) {
        this.flightInformation = flightInformation;
    }

    public void setHotelInformation(String hotelInformation) {
        this.hotelInformation = hotelInformation;
    }

    public void setExcursionInformation(String excursionInformation) {
        this.excursionInformation = excursionInformation;
    }

    public String getFlightInformation() {
        return flightInformation;
    }

    public String getHotelInformation() {
        return hotelInformation;
    }

    public String getExcursionInformation() {
        return excursionInformation;
    }
}
